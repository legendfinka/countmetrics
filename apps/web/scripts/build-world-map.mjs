// Makes the country shapes for the world map. Run it with: pnpm --filter web build:map
// Data: Natural Earth (public domain), packaged as "world-atlas".
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoCentroid, geoNaturalEarth1, geoPath } from "d3-geo";
import countries from "i18n-iso-countries";
import { feature } from "topojson-client";

const WIDTH = 960;
const HEIGHT = 480;
// Numeric ISO country codes
const ANTARCTICA = "010";
const RUSSIA = "643";
const UKRAINE = "804";

const require = createRequire(import.meta.url);
const topology = require("world-atlas/countries-110m.json");
const all = feature(topology, topology.objects.countries).features;
const shapes = all.filter((country) => country.id !== ANTARCTICA);

/** The data draws Crimea as part of Russia. It is part of Ukraine, so we move it there. */
function moveCrimeaToUkraine() {
  const russia = shapes.find((country) => country.id === RUSSIA);
  const ukraine = shapes.find((country) => country.id === UKRAINE);
  const isCrimea = (coordinates) => {
    const [lon, lat] = geoCentroid({ type: "Polygon", coordinates });
    return lon > 32 && lon < 37 && lat > 44 && lat < 46.5;
  };

  const crimea = russia.geometry.coordinates.filter(isCrimea);
  if (crimea.length !== 1) {
    throw new Error(`Expected one Crimea shape in Russia, found ${crimea.length}`);
  }
  russia.geometry.coordinates = russia.geometry.coordinates.filter((part) => !isCrimea(part));

  const own =
    ukraine.geometry.type === "Polygon"
      ? [ukraine.geometry.coordinates]
      : ukraine.geometry.coordinates;
  ukraine.geometry = { type: "MultiPolygon", coordinates: [...own, ...crimea] };
}

moveCrimeaToUkraine();

const projection = geoNaturalEarth1().fitSize([WIDTH, HEIGHT], {
  type: "FeatureCollection",
  features: shapes,
});
// One decimal is enough, and keeps the file small
const toPath = geoPath(projection).digits(1);

const lines = shapes.map((country) => {
  // A few areas have no country code. They are drawn, but never get a colour.
  const code = (country.id && countries.numericToAlpha2(country.id)) || null;
  return `  { code: ${JSON.stringify(code)}, d: ${JSON.stringify(toPath(country))} },`;
});

writeFileSync(
  new URL("../src/features/dashboard/world-shapes.ts", import.meta.url),
  `// Generated by scripts/build-world-map.mjs. Don't edit by hand.
export const MAP_VIEW_BOX = "0 0 ${WIDTH} ${HEIGHT}";

export const WORLD_SHAPES: { code: string | null; d: string }[] = [
${lines.join("\n")}
];
`,
);
console.log(`Saved ${lines.length} country shapes.`);
